-- Funciones
CREATE OR REPLACE FUNCTION public.reabrir_propuesta_modificada()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    IF OLD.estado IN ('aprobada', 'enviada')
       AND NEW.estado = OLD.estado
       AND (to_jsonb(NEW) - ARRAY['estado', 'aprobado_por', 'fecha_aprobacion', 'motivo_rechazo'])
           IS DISTINCT FROM
           (to_jsonb(OLD) - ARRAY['estado', 'aprobado_por', 'fecha_aprobacion', 'motivo_rechazo'])
    THEN
        NEW.estado := 'pendiente_aprobacion';
        NEW.aprobado_por := NULL;
        NEW.fecha_aprobacion := NULL;
    END IF;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.validar_evento_confirmado()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    IF NEW.estado IN (
        'aceptada',
        'confirmado',
        'preparacion',
        'realizado'
    ) THEN
        IF NEW.fecha IS NULL
           OR NEW.sede_prevista IS NULL
           OR TRIM(NEW.sede_prevista) = ''
           OR NEW.cant_asistentes_estimada IS NULL
           OR NEW.cant_asistentes_estimada <= 0 THEN
            RAISE EXCEPTION
                'Para aceptar o confirmar el evento se requiere fecha, sede y cantidad estimada de asistentes válida.';
        END IF;
    END IF;

    RETURN NEW;
END;
$function$;

-- Triggers
CREATE TRIGGER trg_validar_evento_confirmado BEFORE INSERT OR UPDATE OF estado, fecha, sede_prevista, cant_asistentes_estimada ON public.evento FOR EACH ROW EXECUTE FUNCTION validar_evento_confirmado();
CREATE TRIGGER trg_reabrir_propuesta_modificada BEFORE UPDATE ON public.propuesta FOR EACH ROW EXECUTE FUNCTION reabrir_propuesta_modificada();

